describe('K1 — cấu trúc bộ cũ không mở nổi', () => {
  it('nhiều route trong một tệp', () => {
    const src = `- route:
    id: r1
    from:
      uri: direct:a
      steps:
        - log:
            message: a
- route:
    id: r2
    from:
      uri: direct:b
      steps:
        - log:
            message: b`;
    const res = deserialize(src);
    expect(res.entities).toHaveLength(2);
    expect(res.entities.map(e=>e.id)).toEqual(['r1','r2']);
    const out = serialize(res, src);
    expect(out).toContain('r1');
    expect(out).toContain('r2');
  });

  it('Kamelet', () => {
    const src = `apiVersion: camel.apache.org/v1
kind: Kamelet
metadata:
  name: my-source
spec:
  template:
    from:
      uri: timer:tick
      steps:
        - to:
            uri: kamelet:sink`;
    const res = deserialize(src);
    expect(res.kind).toBe('Kamelet');
    const out = serialize(res, src);
    expect(out).toContain('kind: Kamelet');
    expect(out).toContain('timer:tick');
    expect(out).toContain('kamelet:sink');
    expect(out).toContain('my-source');
  });

  it('Pipe', () => {
    const src = `apiVersion: camel.apache.org/v1
kind: Pipe
metadata:
  name: my-pipe
spec:
  source:
    ref:
      kind: Kamelet
      name: timer-source
  sink:
    ref:
      kind: Kamelet
      name: log-sink`;
    const res = deserialize(src);
    expect(res.kind).toBe('Pipe');
    const out = serialize(res, src);
    expect(out).toContain('timer-source');
    expect(out).toContain('log-sink');
  });

  it('routeConfiguration', () => {
    const src = `- routeConfiguration:
    id: rc
    onException:
      - exception:
          - java.lang.Exception
        handled:
          constant: "true"`;
    const res = deserialize(src);
    expect(res.entities).toHaveLength(1);
    const out = serialize(res, src);
    expect(out).toContain('java.lang.Exception');
  });
});

describe('K1 — không ghi trùng khóa ngôn ngữ', () => {
  /**
   * `constant: "x"` là chuỗi nên rơi vào `props`, còn `simple: {expression: …}` rơi vào
   * `rest`. Dọn thiếu một bên thì bước ghi ra **hai lần** cùng một biểu thức.
   */
  it('setBody constant chỉ ghi một lần', () => {
    const src = `- route:
    id: r
    from:
      uri: direct:a
      steps:
        - setBody:
            constant: "xin-chao"`;
    const out = rt(src);
    expect(out.match(/constant:/g) ?? []).toHaveLength(1);
    expect(out.match(/xin-chao/g) ?? []).toHaveLength(1);
  });

  it('mọi ngôn ngữ chỉ ghi một lần và giữ đúng ngôn ngữ', () => {
    for (const lang of ['constant','simple','csimple','jsonpath','groovy','xpath']) {
      const src = `- route:
    id: r
    from:
      uri: direct:a
      steps:
        - setBody:
            ${lang}: "gia-tri"`;
      const out = rt(src);
      expect(out.match(/gia-tri/g) ?? [], `${lang} ghi trùng`).toHaveLength(1);
      expect(out, `${lang} đổi ngôn ngữ`).toContain(`${lang}:`);
    }
  });
});

describe('K1 — tệp thật trong repo (N-9 tương thích ngược)', () => {
  const entries = Object.entries(REAL_FILES);

  it('tìm thấy tệp route thật để kiểm', () => {
    expect(entries.length).toBeGreaterThan(0);
  });

  for (const [path, src] of entries) {
    it(`mở và ghi lại không mất dữ liệu: ${path.split('/').pop()}`, () => {
      const out = serialize(deserialize(src), src);

      // Comment — kể cả dòng xuất xứ kiểm toán — phải còn nguyên (BR-D-06).
      for (const c of src.match(/^\s*#.*/gm) ?? []) {
        expect(out, `mất comment: ${c.trim()}`).toContain(c.trim());
      }
      // Mọi URI phải còn nguyên.
      for (const m of src.match(/uri:\s*["']?([^"'\n]+)/g) ?? []) {
        const v = m.replace(/uri:\s*["']?/, '').trim();
        expect(out, `mất uri ${v}`).toContain(v);
      }
      // Không sinh khối rỗng — dấu hiệu mất cấu trúc như lỗi #6.
      expect(out, 'có khối rỗng').not.toMatch(/:\s*\{\}\s*$/m);
    });
  }
});

describe('K1-8 — round-trip nguyên vẹn trên tệp phức tạp', () => {
  /**
   * Cổng ra của K1: một tệp gom đủ thứ lõi cũ làm hỏng — `doTry` ba khe, `choice` nhiều
   * nhánh, EIP lồng trong EIP, nhiều route một tệp, comment ở đầu — phải quay vòng
   * **không mất một mẩu nào**.
   */
  const COMPLEX = `# Tệp nghiệm thu K1 — không được mất gì
- route:
    id: phuc-tap
    from:
      uri: direct:vao
      steps:
        - doTry:
            steps:
              - to:
                  uri: http://dich-vu-ngoai
              - split:
                  simple: \${body}
                  steps:
                    - log:
                        message: tung-phan-tu
            doCatch:
              - exception:
                  - java.io.IOException
                steps:
                  - log:
                      message: loi-mang
              - exception:
                  - java.lang.Exception
                steps:
                  - log:
                      message: loi-khac
            doFinally:
              steps:
                - log:
                    message: don-dep
        - choice:
            when:
              - simple: \${header.loai} == 'A'
                steps:
                  - multicast:
                      steps:
                        - to:
                            uri: kafka:chu-de-1
                        - to:
                            uri: kafka:chu-de-2
              - simple: \${header.loai} == 'B'
                steps:
                  - setBody:
                      constant: loai-B
            otherwise:
              steps:
                - log:
                    message: khong-ro-loai
- route:
    id: phuc-tap-2
    from:
      uri: direct:vao-2
      steps:
        - log:
            message: route-thu-hai`;

  it('giữ đủ mọi giá trị, không sinh khối rỗng', () => {
    const out = rt(COMPLEX);
    const phaiCon = [
      'Tệp nghiệm thu K1',
      'http://dich-vu-ngoai', 'tung-phan-tu',
      'java.io.IOException', 'loi-mang',
      'java.lang.Exception', 'loi-khac',
      'don-dep',
      'kafka:chu-de-1', 'kafka:chu-de-2',
      'loai-B', 'khong-ro-loai',
      'phuc-tap', 'phuc-tap-2', 'route-thu-hai',
      'direct:vao', 'direct:vao-2',
    ];
    for (const v of phaiCon) expect(out, `mất "${v}"`).toContain(v);
    expect(out, 'có khối rỗng — dấu hiệu mất cấu trúc').not.toMatch(/:\s*\{\}\s*$/m);
  });

  it('quay vòng hai lần cho kết quả y hệt (ổn định, không bào mòn dần)', () => {
    const mot = rt(COMPLEX);
    const hai = serialize(deserialize(mot), mot);
    expect(hai).toBe(mot);
  });

  it('giữ đúng hai route và đúng ba khe của doTry', () => {
    const res = deserialize(COMPLEX);
    expect(res.entities).toHaveLength(2);
    const doTry = res.entities[0].steps.find((s) => s.name === 'doTry')!;
    expect(doTry.branches.map((b) => b.slot).sort()).toEqual(['doCatch','doCatch','doFinally','steps']);
  });
});
