import { describe, expect, it } from 'vitest';
import { deserialize } from './deserialize';
import { serialize } from './serialize';

/**
 * Bản sao các tệp route thật của kho mã, đặt trong `__fixtures__/`.
 *
 * Vì sao chép vào đây thay vì đọc thẳng `routes/`: console là ứng dụng trình duyệt,
 * **cố ý không cài `@types/node`** (đọc bằng `node:fs` làm `tsc --noEmit` đỏ), và Vite
 * chặn nạp tệp ngoài gốc dự án. Kịch bản `npm run check:fixtures` đối chiếu bản sao với
 * bản gốc để bản sao không âm thầm lạc hậu.
 */
const REAL_FILES = import.meta.glob('./__fixtures__/*.camel.yaml', {
  query: '?raw',
  import: 'default',
  eager: true,
}) as Record<string, string>;

const rt = (s: string) => serialize(deserialize(s), s);

describe('K1 — cấu trúc lồng không còn mất (lỗi #6)', () => {
  it('doTry giữ cả steps được bảo vệ lẫn doCatch', () => {
    const src = `- route:
    id: r
    from:
      uri: direct:a
      steps:
        - doTry:
            steps:
              - to:
                  uri: http://x
            doCatch:
              - exception:
                  - java.io.IOException
                steps:
                  - log:
                      message: loi-io`;
    const out = rt(src);
    expect(out).toContain('http://x');
    expect(out).toContain('doCatch');
    expect(out).toContain('java.io.IOException');
    expect(out).toContain('loi-io');
    expect(out).not.toMatch(/doTry:\s*\{\}/);
  });

  it('loadBalance / multicast giữ nhánh', () => {
    for (const eip of ['loadBalance','multicast']) {
      const src = `- route:
    id: r
    from:
      uri: direct:a
      steps:
        - ${eip}:
            steps:
              - to:
                  uri: http://x1
              - to:
                  uri: http://x2`;
      const out = rt(src);
      expect(out, eip).toContain('http://x1');
      expect(out, eip).toContain('http://x2');
      expect(out, eip).not.toMatch(new RegExp(`${eip}:\\s*\\{\\}`));
    }
  });

  it('choice nhiều when giữ đủ điều kiện', () => {
    const src = `- route:
    id: r
    from:
      uri: direct:a
      steps:
        - choice:
            when:
              - simple: "\${header.a} == 1"
                steps:
                  - log:
                      message: mot
              - simple: "\${header.a} == 2"
                steps:
                  - log:
                      message: hai
            otherwise:
              steps:
                - log:
                    message: khac`;
    const out = rt(src);
    expect(out).toContain('mot');
    expect(out).toContain('hai');
    expect(out).toContain('khac');
    expect(out).toMatch(/== 1/);
    expect(out).toMatch(/== 2/);
  });
});

describe('K1 — dạng khối đúng với Camel thật', () => {
  /**
   * `otherwise`/`doFinally` là **đối tượng bọc `steps`**, không phải danh sách trần.
   * Ghi sai dạng thì Camel 4.18.2 từ chối nạp: `Unsupported type: SEQUENCE`.
   * Lược đồ vendor **không** phát hiện được lỗi này (thuộc tính `steps` của
   * `otherwise` khai là null), nên chỉ có test này chặn được.
   */
  it('otherwise ghi ra dạng đối tượng bọc steps, không phải danh sách trần', () => {
    const src = `- route:
    id: r
    from:
      uri: direct:a
      steps:
        - choice:
            when:
              - simple: "\${header.a} == 1"
                steps:
                  - log:
                      message: mot
            otherwise:
              steps:
                - log:
                    message: khac`;
    const out = rt(src);
    expect(out).toMatch(/otherwise:\s*\n\s*steps:/);
    // Dạng sai từng làm Camel chết: `otherwise:` theo ngay sau là gạch đầu dòng.
    expect(out).not.toMatch(/otherwise:\s*\n\s*-\s/);
  });

  it('doFinally cũng là đối tượng bọc steps', () => {
    const src = `- route:
    id: r
    from:
      uri: direct:a
      steps:
        - doTry:
            steps:
              - to:
                  uri: http://x
            doFinally:
              steps:
                - log:
                    message: cuoi`;
    const out = rt(src);
    expect(out).toMatch(/doFinally:\s*\n\s*steps:/);
    expect(out).not.toMatch(/doFinally:\s*\n\s*-\s/);
  });
});

