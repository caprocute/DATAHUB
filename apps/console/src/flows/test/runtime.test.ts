import { describe, expect, it } from 'vitest'
import {
  buildCurl,
  endpointUrl,
  extractSqlParams,
  liveProxyPath,
  parseHttpEntry,
  readFromUri,
} from './runtime'

const YAML = `# Generated by lgsp-control routes publish (WP-23)
- route:
    id: tra-cuu-cong-dan
    from:
      uri: platform-http:/demo/cong-dan?httpMethodRestrict=GET
      steps:
        - to:
            uri: sql:SELECT x FROM ph06.cong_dan WHERE (:#tinh = '' OR tinh_thanh = :#tinh)?outputType=SelectList
        - transform: {}
`

describe('runtime — điểm chạy thật của luồng', () => {
  it('đọc from.uri từ định nghĩa đã publish (kể cả có comment header)', () => {
    expect(readFromUri(YAML)).toBe('platform-http:/demo/cong-dan?httpMethodRestrict=GET')
  })

  it('YAML hỏng hoặc không có route thì trả null, không ném', () => {
    expect(readFromUri('::::')).toBeNull()
    expect(readFromUri('- beans: []')).toBeNull()
  })

  it('tách path + method từ platform-http, mặc định GET', () => {
    expect(parseHttpEntry('platform-http:/demo/cong-dan?httpMethodRestrict=GET,POST')).toMatchObject({
      path: '/demo/cong-dan',
      method: 'GET',
    })
    expect(parseHttpEntry('platform-http:/demo/x').method).toBe('GET')
  })

  it('rest: lấy method ở giữa và path ở cuối', () => {
    expect(parseHttpEntry('rest:get:/api/v1/tai-nguyen')).toMatchObject({
      path: '/api/v1/tai-nguyen',
      method: 'GET',
    })
  })

  it('chặng tiếp nhận không phải HTTP thì path rỗng — không dựng được URL', () => {
    const entry = parseHttpEntry('direct:tra-cuu')
    expect(entry.path).toBe('')
    expect(endpointUrl('camel-dancu', entry)).toBeNull()
  })

  it('gom tham số :#ten trong SQL, không lặp', () => {
    expect(extractSqlParams(YAML)).toEqual(['tinh'])
  })

  it('endpointUrl ghép base theo targetSystem; hệ lạ thì null', () => {
    const entry = parseHttpEntry('platform-http:/demo/cong-dan')
    expect(endpointUrl('camel-dancu', entry)).toBe('http://localhost:8088/demo/cong-dan')
    expect(endpointUrl('he-la', entry)).toBeNull()
  })

  it('curl GET mồi sẵn --data-urlencode cho từng tham số SQL', () => {
    const c = buildCurl('http://localhost:8088/demo/cong-dan', 'GET', ['tinh'])
    expect(c).toContain('--get')
    expect(c).toContain("--data-urlencode 'tinh='")
    expect(c).toContain("'http://localhost:8088/demo/cong-dan'")
  })

  it('curl POST kèm body và Content-Type', () => {
    const c = buildCurl('http://localhost:8088/x', 'POST', [], '{"a":1}')
    expect(c).toContain('-X POST')
    expect(c).toContain(`-d '{"a":1}'`)
  })

  it('liveProxyPath đi qua /runtime/<hệ đích> và giữ query', () => {
    const entry = parseHttpEntry('platform-http:/demo/cong-dan')
    expect(liveProxyPath('camel-dancu', entry, 'tinh=Đà Nẵng')).toBe(
      '/runtime/camel-dancu/demo/cong-dan?tinh=Đà Nẵng',
    )
    expect(liveProxyPath('camel-dancu', entry, '')).toBe('/runtime/camel-dancu/demo/cong-dan')
  })
})
