package vn.lgsp.control.routes.internal;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * Ghi Camel YAML vào {@code routes/<routeCode>/route.camel.yaml} và (tuỳ chọn) git commit DEV.
 */
@Component
class GitOpsPublisher {

  private final Path routesDir;
  private final Path repoRoot;
  private final boolean commitEnabled;
  private final String authorName;
  private final String authorEmail;

  GitOpsPublisher(
      @Value("${lgsp.gitops.routes-dir:routes}") String routesDir,
      @Value("${lgsp.gitops.commit-enabled:false}") boolean commitEnabled,
      @Value("${lgsp.gitops.author-name:lgsp-bot}") String authorName,
      @Value("${lgsp.gitops.author-email:lgsp-bot@local.dev}") String authorEmail) {
    this.repoRoot = resolveRepoRoot();
    this.routesDir = resolveUnderRepo(repoRoot, routesDir);
    this.commitEnabled = commitEnabled;
    this.authorName = authorName;
    this.authorEmail = authorEmail;
  }

  record PublishResult(String gitPath, String commitRef) {}

  PublishResult publish(String routeCode, int versionNo, String yaml) {
    try {
      Path dir = routesDir.resolve(routeCode);
      Files.createDirectories(dir);
      Path target = dir.resolve("route.camel.yaml");
      String header =
          "# Generated by lgsp-control routes publish (WP-23)\n"
              + "# routeCode="
              + routeCode
              + " version="
              + versionNo
              + "\n";
      Files.writeString(target, header + yaml.strip() + "\n", StandardCharsets.UTF_8);
      String relative = repoRoot.relativize(target).toString().replace('\\', '/');
      String ref = commitEnabled ? tryGitCommit(relative, routeCode, versionNo) : contentRef(yaml);
      return new PublishResult(relative, ref);
    } catch (IOException e) {
      throw new IllegalStateException("không ghi được route GitOps: " + e.getMessage(), e);
    }
  }

  private String tryGitCommit(String relativePath, String routeCode, int versionNo) {
    if (!Files.isDirectory(repoRoot.resolve(".git"))) {
      return contentRef(relativePath);
    }
    try {
      runGit(List.of("add", "--", relativePath));
      int commitExit =
          runGit(
              List.of(
                  "-c",
                  "user.name=" + authorName,
                  "-c",
                  "user.email=" + authorEmail,
                  "commit",
                  "-m",
                  "chore(routes): publish " + routeCode + " v" + versionNo));
      String head = runGitCapture(List.of("rev-parse", "HEAD"));
      if (commitExit != 0 && head.isBlank()) {
        return contentRef(relativePath);
      }
      return head.isBlank() ? contentRef(relativePath) : head;
    } catch (Exception e) {
      return contentRef(relativePath + ":" + e.getMessage());
    }
  }

  private int runGit(List<String> args) throws IOException, InterruptedException {
    List<String> cmd = new ArrayList<>();
    cmd.add("git");
    cmd.addAll(args);
    ProcessBuilder pb = new ProcessBuilder(cmd);
    pb.directory(repoRoot.toFile());
    pb.redirectErrorStream(true);
    Process p = pb.start();
    try (BufferedReader r =
        new BufferedReader(new InputStreamReader(p.getInputStream(), StandardCharsets.UTF_8))) {
      while (r.readLine() != null) {
        // discard bot output
      }
    }
    if (!p.waitFor(30, TimeUnit.SECONDS)) {
      p.destroyForcibly();
      return -1;
    }
    return p.exitValue();
  }

  private String runGitCapture(List<String> args) throws IOException, InterruptedException {
    List<String> cmd = new ArrayList<>();
    cmd.add("git");
    cmd.addAll(args);
    ProcessBuilder pb = new ProcessBuilder(cmd);
    pb.directory(repoRoot.toFile());
    pb.redirectErrorStream(true);
    Process p = pb.start();
    StringBuilder sb = new StringBuilder();
    try (BufferedReader r =
        new BufferedReader(new InputStreamReader(p.getInputStream(), StandardCharsets.UTF_8))) {
      String line;
      while ((line = r.readLine()) != null) {
        if (!sb.isEmpty()) {
          sb.append('\n');
        }
        sb.append(line);
      }
    }
    if (!p.waitFor(30, TimeUnit.SECONDS)) {
      p.destroyForcibly();
      return "";
    }
    return sb.toString().trim();
  }

  private static String contentRef(String yaml) {
    return "file:" + shortHash(yaml);
  }

  private static String shortHash(String s) {
    try {
      byte[] dig = MessageDigest.getInstance("SHA-256").digest(s.getBytes(StandardCharsets.UTF_8));
      return HexFormat.of().formatHex(dig).substring(0, 12);
    } catch (Exception e) {
      return Integer.toHexString(s.hashCode());
    }
  }

  private static Path resolveRepoRoot() {
    Path cwd = Path.of("").toAbsolutePath().normalize();
    if (Files.isDirectory(cwd.resolve("routes")) && Files.isDirectory(cwd.resolve("deploy"))) {
      return cwd;
    }
    Path up = cwd.getParent() != null ? cwd.getParent().getParent() : cwd;
    if (up != null
        && Files.isDirectory(up.resolve("routes"))
        && Files.isDirectory(up.resolve("deploy"))) {
      return up;
    }
    return cwd;
  }

  private static Path resolveUnderRepo(Path repoRoot, String configured) {
    Path p = Path.of(configured);
    if (p.isAbsolute()) {
      return p.normalize();
    }
    return repoRoot.resolve(configured).normalize();
  }
}
