package vn.lgsp.control.catalog.internal;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/** Ghi route APISIX declarative vào Git path — không gọi Admin API. */
@Component
class ApisixRouteWriter {

  private final Path routesDir;

  ApisixRouteWriter(
      @Value("${lgsp.apisix.routes-dir:deploy/apisix/routes}") String routesDir) {
    this.routesDir = resolveRoutesDir(routesDir);
  }

  String writeRoute(String serviceCode, String publicPath, String upstreamUrl) {
    try {
      Files.createDirectories(routesDir);
      String fileName = serviceCode.replaceAll("[^a-zA-Z0-9._-]", "-") + ".yaml";
      Path target = routesDir.resolve(fileName);
      String yaml =
          """
          # Generated by lgsp-control catalog publish — do not edit by hand in PROD
          routes:
            - id: %s
              name: %s
              uri: %s
              methods: [GET, POST, PUT, DELETE, OPTIONS]
              upstream:
                type: roundrobin
                nodes:
                  "%s": 1
              plugins:
                cors:
                  allow_origins: "**"
                  allow_methods: "**"
                  allow_headers: "**"
                limit-count:
                  count: 100
                  time_window: 60
                  rejected_code: 429
          """
              .formatted(serviceCode, serviceCode, publicPath, stripSchemeHostPort(upstreamUrl));
      Files.writeString(target, yaml, StandardCharsets.UTF_8);
      return target.toString();
    } catch (IOException e) {
      throw new IllegalStateException("không ghi được route APISIX: " + e.getMessage(), e);
    }
  }

  private static Path resolveRoutesDir(String configured) {
    Path configuredPath = Path.of(configured);
    if (configuredPath.isAbsolute()) {
      return configuredPath.normalize();
    }
    Path cwd = Path.of("").toAbsolutePath().normalize();
    if (Files.isDirectory(cwd.resolve("deploy"))) {
      return cwd.resolve(configured).normalize();
    }
    // spring-boot:run từ apps/control
    Path repoRoot = cwd.getParent() != null ? cwd.getParent().getParent() : cwd;
    if (repoRoot != null && Files.isDirectory(repoRoot.resolve("deploy"))) {
      return repoRoot.resolve(configured).normalize();
    }
    return cwd.resolve(configured).normalize();
  }

  private static String stripSchemeHostPort(String upstreamUrl) {
    String u = upstreamUrl.replaceFirst("^https?://", "");
    return u.endsWith("/") ? u.substring(0, u.length() - 1) : u;
  }
}
